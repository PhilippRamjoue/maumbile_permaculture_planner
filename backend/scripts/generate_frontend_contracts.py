"""Generate the imagery response type and fixture from the backend contract.

Run from backend: python scripts/generate_frontend_contracts.py [--check].
Keep this deliberately scoped; add other response models as their frontend consumers arrive.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.modules.imagery.providers import EsriWorldImageryProvider  # noqa: E402
from app.modules.imagery.schemas import ImageryMeta  # noqa: E402

FRONTEND = Path(__file__).resolve().parents[2] / "frontend" / "src"


def ts_type(schema: dict[str, Any]) -> str:
    if "anyOf" in schema:
        return " | ".join(ts_type(part) for part in schema["anyOf"])
    return {"string": "string", "integer": "number", "boolean": "boolean", "null": "null"}[
        schema["type"]
    ]


def outputs() -> dict[Path, str]:
    properties = ImageryMeta.model_json_schema()["properties"]
    declaration = "// Generated by backend/scripts/generate_frontend_contracts.py. Do not edit.\n"
    declaration += "export interface ImageryMeta {\n"
    # FastAPI serializes default-valued fields too, so every response key is present.
    declaration += "".join(f"  {name}: {ts_type(prop)};\n" for name, prop in properties.items())
    declaration += "}\n"
    provider = EsriWorldImageryProvider()
    fixture = ImageryMeta(
        covered=True,
        provider_key=provider.key,
        attribution=provider.attribution,
        license=provider.license,
        terms_url=provider.terms_url,
        max_zoom=provider.max_zoom,
        cacheable=provider.cacheable,
        tile_url_template="/api/v1/sites/11111111-1111-1111-1111-111111111111/imagery/{z}/{x}/{y}.png",
    )
    return {
        FRONTEND / "entities/generated/imagery.ts": declaration,
        FRONTEND / "shared/testing/imagery-contract.json": json.dumps(
            fixture.model_dump(), indent=2, ensure_ascii=False
        )
        + "\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale API contract: {path}. Run this script without --check.")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
