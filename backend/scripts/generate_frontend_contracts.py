def outputs() -> dict[Path, str]:
    declaration = HEADER + ts_interface("ImageryMeta", ImageryMeta.model_json_schema())
    provider = EsriWorldImageryProvider()
    fixture = ImageryMeta(
        covered=True,
        provider_key=provider.key,
        attribution=provider.attribution,
        license=provider.license,
        terms_url=provider.terms_url,
        max_zoom=provider.max_zoom,
        cacheable=provider.cacheable,
        tile_url_template="/api/v1/sites/11111111-1111-1111-1111-111111111111/imagery/{z}/{x}/{y}.png",
    )
    return {
        FRONTEND / "entities/generated/imagery.ts": declaration,
        FRONTEND / "shared/testing/imagery-contract.json": json.dumps(
            fixture.model_dump(), indent=2, ensure_ascii=False
        )
        + "\n",
        FRONTEND / "entities/generated/terrain.ts": terrain_declaration(),
        FRONTEND / "shared/testing/terrain-contract.json": json.dumps(
            terrain_fixture().model_dump(mode="json"), indent=2, ensure_ascii=False
        )
        + "\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale API contract: {path}. Run this script without --check.")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Fixed LF endings keep the output identical across platforms (and `--check` stable).
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
